import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {server} from '../apps/control-command-center/server.mjs';
import {readFileSync} from 'node:fs';
const registry=JSON.parse(readFileSync(new URL('../packages/contracts/workspaces.json',import.meta.url)));
const http=server();await new Promise(resolve=>http.listen(0,'127.0.0.1',resolve));
let browser;
try{
 browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:'+http.address().port);
 await page.waitForFunction(()=>document.querySelectorAll('#workspace option').length===18);
 assert.equal(await page.title(),'b3Ɛq::One');
 assert.equal(await page.locator('#environments button').count(),16);
 await page.locator('#environments button').last().click();
 const context=await page.locator('#context').textContent();
 for(const w of registry.workspaces){
  await page.locator('#workspace').selectOption(w.id);
  assert.equal(await page.locator('#title').textContent(),w.name);
  assert.equal(await page.locator('#panels article').count(),w.panels.length);
  assert.equal(await page.locator('#context').textContent(),context);
 }
 await page.locator('#theme').selectOption('dark');
 assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
 await page.locator('#workspace').selectOption('W13');
 await page.getByRole('button',{name:'Validate workflow',exact:true}).click();
 assert.match(await page.locator('#panels pre').last().textContent(),/executable.*false/);
 await page.locator('#toggle').click();
 assert.equal(await page.locator('#command').isVisible(),false);
 assert.equal(await page.getByRole('button',{name:'Validate workflow',exact:true}).count(),0);
 assert.match(await page.locator('#panels').textContent(),/Evidence unavailable/);
 await page.locator('#toggle').click();
 await page.locator('#intent').fill('Create demo academia stack');
 await page.getByRole('button',{name:'Preview intent',exact:true}).click();
 await page.getByRole('button',{name:'Evaluate provisioning simulation',exact:true}).click();
 await page.waitForFunction(()=>[...document.querySelectorAll('pre')].some(p=>p.textContent.includes('"executable": false')));
 await page.locator('#workspace').selectOption('W01');
 const headings=()=>page.locator('#panels article h2').allTextContents();
 const original=await headings();
 await page.locator('#panels article').first().getByRole('button',{name:'Later',exact:true}).click();
 const reordered=await headings();
 assert.notDeepEqual(reordered,original);
 const first=page.locator('#panels article').first();
 const span=await first.getAttribute('data-span');
 await first.getByRole('button',{name:'Resize',exact:true}).click();
 const resized=await first.getAttribute('data-span');
 assert.notEqual(resized,span);
 await first.getByRole('button',{name:'Collapse',exact:true}).click();
 await page.getByRole('button',{name:'Lock layout',exact:true}).click();
 assert.equal(await first.getByRole('button',{name:'Resize',exact:true}).isDisabled(),true);
 await page.locator('#toggle').click();
 assert.deepEqual(await headings(),original);
 await page.locator('#toggle').click();
 assert.deepEqual(await headings(),reordered);
 await page.reload();
 await page.waitForFunction(()=>document.querySelectorAll('#workspace option').length===18);
 await page.locator('#workspace').selectOption('W01');
 assert.deepEqual(await headings(),reordered);
 assert.equal(await first.getAttribute('data-span'),resized);
 assert.equal(await first.getByRole('button',{name:'Expand',exact:true}).count(),1);
 await page.getByRole('button',{name:'Unlock layout',exact:true}).click();
 await page.getByRole('button',{name:'Restore factory layout',exact:true}).click();
 assert.deepEqual(await headings(),original);
 await page.waitForFunction(()=>document.querySelectorAll('#environment option').length===16);
 await page.locator('#account-toggle').click();
 assert.equal(await page.locator('#account-menu').isVisible(),true);
 assert.ok((await page.locator('#account-menu').boundingBox()).width<=240);
 await page.locator('#workspace').selectOption('W08');
 await page.locator('#environment').selectOption({index:1});
 await page.locator('#theme').selectOption('light');
 await page.locator('#toggle').click();
 assert.equal(await page.locator('#account-menu').isVisible(),true);
 await page.locator('#toggle').click();
 await page.getByRole('button',{name:'Close account',exact:true}).click();
 await page.locator('#dock-toggle').click();
 for(const name of ['Environment Explorer','Object Inspector','Console & Activity'])await page.locator('#dock-menu').getByLabel(name,{exact:true}).uncheck();
 for(const id of ['environments','object-inspector','activity-console'])assert.equal(await page.locator('#'+id).isVisible(),false);
 for(const id of ['workspace','environment','theme','toggle','account-toggle','dock-toggle'])assert.equal(await page.locator('#'+id).isVisible(),true);
 await page.getByRole('button',{name:'Restore all docks',exact:true}).click();
 for(const id of ['environments','object-inspector','activity-console'])assert.equal(await page.locator('#'+id).isVisible(),true);
 await page.locator('#dock-toggle').click();
 const inspector=page.locator('#object-inspector');
 await inspector.getByLabel('Inspect resource').selectOption('1');
 await inspector.getByLabel('Virtual CPUs').fill('6');
 await inspector.getByRole('button',{name:'Save change plan',exact:true}).click();
 assert.match(await page.locator('#activity-console').textContent(),/independent review required/);
 assert.match(await page.locator('#activity-console pre').last().textContent(),/"executable": false/);
 await page.locator('#toggle').click();
 assert.equal(await inspector.getByLabel('Virtual CPUs').isDisabled(),true);
 assert.equal(await inspector.getByRole('button',{name:'Save change plan',exact:true}).count(),0);
 await page.locator('#toggle').click();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.locator('#workspace').isVisible(),true);
 assert.deepEqual(errors,[]);
 console.log('Browser acceptance passed');
}finally{if(browser)await browser.close();await new Promise(resolve=>http.close(resolve));}

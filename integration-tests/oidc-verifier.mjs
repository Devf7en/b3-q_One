import assert from 'node:assert/strict';
import {generateKeyPair,exportJWK,SignJWT} from 'jose';
import {createOidcVerifier} from '../packages/oidc-verifier/index.mjs';
import {createIdentityBoundary} from '../packages/identity/index.mjs';
const issuer='https://issuer.example',audience='one',jwksUri=issuer+'/jwks';
const key=await generateKeyPair('RS256'), forged=await generateKeyPair('RS256');
const jwk={...await exportJWK(key.publicKey),kid:'fixture',alg:'RS256',use:'sig'};
let requests=0;
const fetcher=async url=>{assert.equal(String(url),jwksUri);requests++;return new Response(JSON.stringify({keys:[jwk]}),{status:200,headers:{'content-type':'application/json'}});};
assert.throws(()=>createOidcVerifier({issuer:'http://issuer.example',audience,jwksUri}));
const verify=createOidcVerifier({issuer,audience,jwksUri,fetcher});
const now=Math.floor(Date.now()/1000);
const sign=(overrides={},privateKey=key.privateKey,typ='at+jwt')=>new SignJWT({iss:issuer,aud:audience,sub:'fixture-user',iat:now,exp:now+300,...overrides}).setProtectedHeader({alg:'RS256',kid:'fixture',typ}).sign(privateKey);
const expected={issuer,audience},valid=await sign();
assert.equal((await verify(valid,expected)).sub,'fixture-user');
for(const token of [await sign({},forged.privateKey),await sign({iss:'https://wrong.example'}),await sign({aud:'wrong'}),await sign({exp:now-1}),await sign({iat:now-1000}),await sign({nbf:now+300}),await sign({},key.privateKey,'JWT'),'invalid'])await assert.rejects(verify(token,expected));
await assert.rejects(verify(valid,{issuer:'https://wrong.example',audience}));
const authenticate=createIdentityBoundary({verifyToken:verify,issuer,audience,findMembership:async ({subject,tenantId})=>subject==='fixture-user'&&tenantId==='tenant-a'?{tenantId,userId:'user-a',role:'operator'}:null});
assert.deepEqual(await authenticate(valid,'tenant-a'),{tenantId:'tenant-a',userId:'user-a',role:'operator'});
await assert.rejects(authenticate(valid,'tenant-b'));
assert.equal(requests,1);
console.log('Signed-token, rejection, JWKS caching and fixture membership acceptance passed');
